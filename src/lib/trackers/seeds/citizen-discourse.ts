export function seedCitizenDiscourseTrackerRow(): TrackerRow {
  const ranked = [...CITIZEN_DISCOURSE_SEED]
    .filter((l) => l.status !== "waiting")
    .sort((a, b) => (b.overall_score ?? 0) - (a.overall_score ?? 0))
    .map((l, i) => ({ ...l, rank: i + 1 }));

  return {
    tracker_type: "citizen_discourse_index",
    created_at: new Date().toISOString(),
    last_updated: new Date().toISOString(),
    item_count: ranked.length,
    snapshot_label: "seed-v2-individuals-only-2026-08",
    deep_dive_summary:
      "Individual citizen journalists and independent reporters only — NGOs, charities, and UN bodies excluded. Ranked on trust, authenticity, rigor, independence, and on-the-ground focus. Not an endorsement.",
    data: {
      regions: {
        americas: ranked.filter((l) => l.region === "Americas"),
        europe: ranked.filter((l) => l.region === "Europe"),
        middle_east: ranked.filter((l) => l.region === "Middle East"),
        global: ranked.filter((l) => l.region === "Global"),
      },
      ranked_leaders: ranked,
    },
  };
}
